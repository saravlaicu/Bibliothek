public class Buch {
    public String Tietel;
    public String Author;
    public double Preis;
    public int Anzahl_Seiten;

    public Buch(String Tietel, String Author, double Preis, int Anzahl_Seiten) {
        this.Tietel=Tietel;
        this.Author= Author;
        this.Preis=Preis;
        this.Anzahl_Seiten=Anzahl_Seiten;
    }


}

